def main():
    p = os.path.join(HERE, "posts.json")
    posts = json.load(open(p, encoding="utf-8"))
    have = set(d["id"] for d in posts["days"])
    add = [d for d in DAYS if d["id"] not in have]
    if not add:
        print("すでに入っています")
        return
    posts["days"].extend(add)
    check.run(posts)                     # 通らなければここで止まる
    json.dump(posts, open(p, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    print("Day 21〜30 を追加しました（全 %d 日分）" % len(posts["days"]))
    for d in add:
        print("  %s  %-12s %s" % (d["id"], d["theme"], d["photo"]))

    # 日付を投稿デスクの記録に入れる
    site = os.path.dirname(HERE)
    import re
    f = os.path.join(site, "index.html")
    t = open(f, encoding="utf-8").read()
    m = re.search(r'(<script id="app-state" type="application/json">)(.*?)(</script>)', t, re.S)
    st = json.loads(m.group(2))
    for i, d in enumerate(add):
        st["dates"][d["id"]] = X_DATES[i]
        st["dates"]["i%02d" % (21 + i)] = IG_DATES[i]
    t = t[:m.start(2)] + json.dumps(st, ensure_ascii=False, separators=(",", ":")) + t[m.end(2):]
    open(f, "w", encoding="utf-8").write(t)
    print("\nX は %s から毎日、Instagram は %s から週3回で日付を入れました"
          % (X_DATES[0], IG_DATES[0]))


if __name__ == "__main__":
    main()
