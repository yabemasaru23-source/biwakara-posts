for d in DAYS:
    d["x"] = d["xv"][0]["text"]
    d["tags"] = list(TAGS)

START = datetime.date(2026, 10, 20)
DATES = {d["id"]: (START + datetime.timedelta(days=i)).isoformat() for i, d in enumerate(DAYS)}


def ig_dates(after, n):
    d, out = datetime.date.fromisoformat(after) + datetime.timedelta(days=1), []
    while len(out) < n:
        if d.weekday() in (0, 2, 4):
            out.append(d.isoformat())
        d += datetime.timedelta(days=1)
    return out


def main():
    p = os.path.join(HERE, "posts.json")
    posts = json.load(open(p, encoding="utf-8"))
    have = {d["id"] for d in posts["days"]}
    add = [d for d in DAYS if d["id"] not in have]
    posts["days"].extend(add)
    check.run(posts)
    json.dump(posts, open(p, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    f = os.path.join(os.path.dirname(HERE), "index.html")
    t = open(f, encoding="utf-8").read()
    m = re.search(r'(<script id="app-state" type="application/json">)(.*?)(</script>)', t, re.S)
    st = json.loads(m.group(2))
    for k, v in DATES.items():
        st["dates"][k] = v
    last_ig = max(v for k, v in st["dates"].items() if k.startswith("i"))
    base = len(posts["days"]) - len(add)
    for n, dt in enumerate(ig_dates(last_ig, len(add))):
        st["dates"]["i%02d" % (base + n + 1)] = dt
    t = t[:m.start(2)] + json.dumps(st, ensure_ascii=False, separators=(",", ":")) + t[m.end(2):]
    open(f, "w", encoding="utf-8").write(t)
    print("X 10/20〜11/2 Day48〜61 を入れました（%d本）" % len(add))


if __name__ == "__main__":
    main()
