def put(did, theme=None, cap=None, xv=None, igv=None, slides=None):
    d = D[did]
    if theme:
        d["theme"] = theme
    if cap:
        d["cap"] = cap
    if xv:
        for v, t in zip(d["xv"], xv):
            v["text"] = t
        d["x"] = xv[0]
    if igv:
        for v, t in zip(d["igv"], igv):
            v["text"] = t
    if slides:
        d["igslides"] = slides


def repl(did, pairs):
    d = D[did]
    s = json.dumps(d, ensure_ascii=False)
    for a, b in pairs:
        s = s.replace(a, b)
    D[did].clear()
    D[did].update(json.loads(s))


